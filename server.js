'use strict';
const express = require('express');
const multer = require('multer');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const app = express();
const PORT = process.env.PORT || 3000;
const ADMIN_PASSWORD = process.env.ADMIN_PASSWORD;
const UPLOAD_CODE = process.env.UPLOAD_CODE;
if (!ADMIN_PASSWORD || !UPLOAD_CODE) { console.error('Please set ADMIN_PASSWORD and UPLOAD_CODE environment variables.'); process.exit(1); }
const dataDir = process.env.DATA_DIR || path.join(__dirname, 'data');
const imgDir = path.join(dataDir, 'photos');
const dbFile = path.join(dataDir, 'photos.json');
fs.mkdirSync(imgDir, { recursive: true });
if (!fs.existsSync(dbFile)) fs.writeFileSync(dbFile, '[]');
const readDb = () => JSON.parse(fs.readFileSync(dbFile, 'utf8'));
const writeDb = (items) => { const tmp = dbFile + '.tmp'; fs.writeFileSync(tmp, JSON.stringify(items, null, 2)); fs.renameSync(tmp, dbFile); };
const equal = (a, b) => {const aa = Buffer.from(String(a || '')); const bb = Buffer.from(String(b || '')); return aa.length === bb.length && crypto.timingSafeEqual(aa, bb);};
const adminAuth = (req, res, next) => equal(req.get('x-admin-password'), ADMIN_PASSWORD) ? next() : res.status(401).json({error:'管理员密码不正确'});
const upload = multer({ storage: multer.memoryStorage(), limits: {fileSize: 12*1024*1024, files: 1} });
app.disable('x-powered-by');
app.use(express.json({limit:'1mb'}));
app.use('/photos', express.static(imgDir, {maxAge:'1h', index:false}));
app.use(express.static(path.join(__dirname, 'public')));
app.get('/api/photos', (req, res) => res.json(readDb().filter(x=>x.approved).slice(-300).reverse()));
app.get('/api/admin/photos', adminAuth, (req, res) => res.json(readDb().slice().reverse()));
app.post('/api/upload', (req,res,next) => upload.single('photo')(req,res,err => err ? next(err) : next()), (req,res) => {
  if (!equal(req.body.code, UPLOAD_CODE)) return res.status(403).json({error:'上传口令不正确'});
  if (!req.file) return res.status(400).json({error:'请选择照片'});
  const b = req.file.buffer;
  const isJpg = b.length>3 && b[0]===0xff && b[1]===0xd8 && b[2]===0xff;
  const isPng = b.length>8 && b.subarray(0,8).equals(Buffer.from('89504e470d0a1a0a','hex'));
  const isWebp = b.length>12 && b.toString('ascii',0,4)==='RIFF' && b.toString('ascii',8,12)==='WEBP';
  if (!isJpg && !isPng && !isWebp) return res.status(400).json({error:'支持 JPG、PNG、WEBP 图片，请将 HEIC 转为 JPG'});
  const ext = isJpg ? 'jpg' : isPng ? 'png' : 'webp';
  const name = crypto.randomUUID()+'.'+ext;
  fs.writeFileSync(path.join(imgDir,name),b,{flag:'wx'});
  const caption = String(req.body.caption || '').trim().slice(0,45);
  const item = {id:crypto.randomUUID(),url:'/photos/'+name,caption,approved:process.env.AUTO_APPROVE==='true',uploadedAt:new Date().toISOString()};
  const photos=readDb(); photos.push(item); writeDb(photos);
  res.json({ok:true,approved:item.approved,message:item.approved?'照片已上墙':'上传成功，等待工作人员审核'});
});
app.post('/api/admin/:id/approve', adminAuth, (req,res) => { const items=readDb();const item=items.find(x=>x.id===req.params.id);if(!item)return res.status(404).json({error:'找不到照片'});item.approved=!!req.body.approved;writeDb(items);res.json({ok:true}); });
app.delete('/api/admin/:id', adminAuth, (req,res) => {let items=readDb();const item=items.find(x=>x.id===req.params.id);if(!item)return res.status(404).json({error:'找不到照片'});items=items.filter(x=>x.id!==req.params.id);writeDb(items); try {fs.unlinkSync(path.join(imgDir,path.basename(item.url)));}catch{}res.json({ok:true});});
app.get('/health',(_,res)=>res.json({ok:true}));
app.use((err,req,res,next)=>res.status(400).json({error:err.code==='LIMIT_FILE_SIZE'?'图片不能超过12MB':(err.message||'上传失败')}));
app.listen(PORT,'0.0.0.0',()=>console.log('Marathon wall running on :'+PORT));
